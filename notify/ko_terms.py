"""차트·매매 용어 번역 보정 (2026-09-28 대표 요청 "차트 용어 번역 보정도 진행하자").

무료 번역기(Google 비공식 → 429 시 MyMemory 폴백)는 매매 용어를 사전적으로 직역한다.
실측(09-28, MyMemory):
  "Moderate Bearish Correction"  → "보통 곰 보정"        (완만한 하락 조정)
  "bear flag" / "bull flag"      → "곰 깃발" / "불 플래그" (하락·상승 깃발형)
  "Bulls defend key support"     → "황소는 … 주요 지지대를" (매수세)
  "Short squeeze"                → "짧은 스퀴즈"          (숏 스퀴즈)
  "Retest of the breakout level" → "분류 수준 재검사"     (돌파 구간 리테스트)
  "Oversold bounce"              → "초과 매도 반송"       (과매도 반등)
  "Double bottom"                → "이중 하단"            (쌍바닥)
영문에 한국어 용어를 미리 끼워 넣는 방식은 번역기가 어순을 깨뜨려(“SUI Moderate가 곧 종료될 수
하락 조정 있음”) 쓰지 않는다 — **번역 결과(한국어)를 사후 보정**한다. 규칙은 긴 구절부터
적용하고, 일반 문장에도 흔한 단어(통합·지원·보정 등)는 매매 문맥 구절로만 바꾼다.
"""

import re

# (패턴, 치환) — 위에서부터 순서대로. 긴·구체적인 구절이 먼저다.
_RULES = [
    # 조정(correction)
    (r"보통\s*곰\s*보정", "완만한 하락 조정"),
    (r"보통\s*황소\s*보정", "완만한 상승 조정"),
    (r"곰\s*보정", "하락 조정"),
    (r"(?:약세|하락|가격)\s*보정", lambda m: m.group(0).replace("보정", "조정")),
    (r"보정\s*(?:단계|국면|구간)", lambda m: m.group(0).replace("보정", "조정")),
    # 깃발형·패턴
    (r"곰\s*(?:깃발|플래그)", "하락 깃발형"),
    (r"(?:황소|불)\s*(?:깃발|플래그)", "상승 깃발형"),
    (r"이중\s*(?:하단|바닥)", "쌍바닥"),
    (r"이중\s*(?:상단|탑|천장)", "쌍봉"),
    (r"역\s*머리와\s*어깨", "역헤드앤숄더"),
    (r"머리와\s*어깨", "헤드앤숄더"),
    (r"오름차순\s*삼각형", "상승 삼각형"),
    (r"내림차순\s*삼각형", "하락 삼각형"),
    (r"떨어지는\s*쐐기", "하락 쐐기"),
    (r"상승하는\s*쐐기", "상승 쐐기"),
    (r"컵\s*(?:과|앤)\s*(?:손잡이|핸들)", "컵앤핸들"),
    (r"(?:불리시|강세)\s*휩핑", "상승 장악형"),
    (r"(?:베어리시|약세)\s*휩핑", "하락 장악형"),
    (r"휩핑", "장악형"),
    # 세력
    (r"곰(?=[은는이가을를의도과와]|\s|$)", "매도세"),
    (r"황소(?=[은는이가을를의도과와]|\s|$)", "매수세"),
    (r"베어스", "매도세"),
    (r"불스(?!\s*아이)", "매수세"),
    (r"불리시", "강세"),
    (r"베어리시", "약세"),
    # 스퀴즈·청산
    (r"짧은\s*스퀴즈", "숏 스퀴즈"),
    (r"긴\s*스퀴즈", "롱 스퀴즈"),
    (r"짧은\s*청산", "숏 청산"),
    (r"긴\s*청산", "롱 청산"),
    # 돌파·리테스트·지지/저항
    (r"분류\s*수준\s*재검사", "돌파 구간 리테스트"),
    (r"(?:돌파|분류)\s*(?:수준|레벨)", "돌파 구간"),
    (r"재검사", "리테스트"),
    (r"키\s*지원", "핵심 지지"),
    (r"주요\s*지지대", "핵심 지지선"),
    (r"지원\s*(?:수준|레벨|구역|영역)", "지지 구간"),
    (r"저항\s*(?:수준|레벨)", "저항선"),
    (r"공급\s*(?:구역|영역|존)", "매도 대기 구간"),
    (r"수요\s*(?:구역|영역|존)", "매수 대기 구간"),
    (r"범위\s*제한", "박스권"),
    (r"범위\s*내(?:에서)?\s*거래", "박스권 거래"),
    # 과매수·과매도·반등
    (r"초과\s*매도", "과매도"),
    (r"초과\s*매수", "과매수"),
    (r"(과매[도수]|반등|되돌림)\s*반송", r"\1 반등"),
    (r"과매도\s*반송", "과매도 반등"),
    (r"구제\s*랠리", "안도 랠리"),
    # 고점·저점 구조
    (r"더\s*높은\s*(?:최저치|저점)", "저점 상승"),
    (r"더\s*낮은\s*(?:최고치|고점)", "고점 하락"),
    (r"더\s*높은\s*(?:최고치|고점)", "고점 갱신"),
    (r"더\s*낮은\s*(?:최저치|저점)", "저점 갱신(하락)"),
    # 기타
    (r"가격이\s*통합(?=되|하|중)", "가격이 수렴"),
    (r"통합\s*구간", "수렴 구간"),
    (r"일일\s*차트", "일봉 차트"),
    (r"주간\s*차트", "주봉 차트"),
    (r"매주\s*(?=(?:상승\s*|하락\s*)?(?:장악형|캔들|종가))", "주봉 "),
    (r"시가\s*총액\s*및\s*안도\s*랠리", "투매 후 안도 랠리"),
    (r"황금\s*십자가", "골든 크로스"),
    (r"죽음의\s*십자가", "데드 크로스"),
    (r"유동성\s*청소", "유동성 스윕"),
    (r"공정\s*가치\s*(?:격차|갭)", "FVG(공정가치갭)"),
    (r"주문\s*블록", "오더블록"),
]
_COMPILED = [(re.compile(p), r) for p, r in _RULES]

# 치환된 용어 뒤 조사 맞춤 — "지지대를"→"지지선를" 같은 어긋남(받침 유무가 바뀜)을 바로잡는다.
_JOSA_PAIRS = {"은": ("은", "는"), "는": ("은", "는"), "이": ("이", "가"), "가": ("이", "가"),
               "을": ("을", "를"), "를": ("을", "를"), "과": ("과", "와"), "와": ("과", "와")}
_TERMS = sorted({r.strip() for _p, r in _RULES if isinstance(r, str) and "\\" not in r},
                key=len, reverse=True)
_JOSA_RX = re.compile("(" + "|".join(re.escape(t) for t in _TERMS if t) + r")(은|는|이|가|을|를|과|와)(?![가-힣])")


def _has_batchim(ch: str) -> bool:
    code = ord(ch) - 0xAC00
    return 0 <= code <= 11171 and code % 28 != 0


def _fix_josa(m) -> str:
    term, josa = m.group(1), m.group(2)
    with_b, without_b = _JOSA_PAIRS[josa]
    return term + (with_b if _has_batchim(term[-1]) else without_b)


def fix_ko_terms(text: str) -> str:
    """번역된 한국어에서 차트·매매 용어 직역을 업계 용어로 바꾼다. 실패해도 원문 유지."""
    if not text:
        return text
    out = text
    for rx, rep in _COMPILED:
        try:
            out = rx.sub(rep, out)
        except Exception:  # noqa: BLE001 - 보정 실패가 뉴스를 죽이면 안 된다
            continue
    try:
        out = _JOSA_RX.sub(_fix_josa, out)
    except Exception:  # noqa: BLE001
        pass
    return out
